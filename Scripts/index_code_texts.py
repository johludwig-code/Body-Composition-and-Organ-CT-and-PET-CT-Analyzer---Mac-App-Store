#!/usr/bin/env python3
"""Write the app's texts for the import's codes from Protocol/index_codes.json.

The database, events and logs carry codes with parameters, never prose
(ADR 0023); the app turns them into US-English text through the String
Catalog. Swift extracts only literal keys, so every code becomes one
`String(localized:defaultValue:)` call in a generated file:

    python3 Scripts/index_code_texts.py           # write the Swift file
    python3 Scripts/index_code_texts.py --check   # fail if it is stale

Codes without a text in the registry (read and error codes, which the app
only counts) get none here either.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "Protocol" / "index_codes.json"
OUTPUT = ROOT / "App" / "Sources" / "BCOAnalyzer" / "Generated" / "IndexCodeTexts.swift"


def _swift_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def render(registry: dict) -> str:
    lines = [
        "// Generated by Scripts/index_code_texts.py from Protocol/index_codes.json.",
        "// Do not edit; run the script after changing the registry.",
        "",
        "import Foundation",
        "",
        "/// The default US-English text of every import code that has one, keyed",
        "/// by group and code. `{name}` in a text is a parameter.",
        "enum IndexCodeTexts {",
        "    static func text(group: String, code: String) -> String? {",
        "        switch (group, code) {",
    ]
    for group, entry in registry["groups"].items():
        for item in entry["codes"]:
            text = item.get("text")
            if not text:
                continue
            key = f"index.{group}.{item['code']}"
            lines.append(
                f"        case ({_swift_string(group)}, {_swift_string(item['code'])}):"
                f" String(localized: {_swift_string(key)}, defaultValue: {_swift_string(text)})"
            )
    lines += ["        default: nil", "        }", "    }", "}", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    rendered = render(json.loads(REGISTRY.read_text()))
    if "--check" in argv:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != rendered:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run Scripts/index_code_texts.py")
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(rendered)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
